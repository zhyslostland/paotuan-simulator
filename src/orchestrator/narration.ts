/**
 * 叙述一致性 —— **核"守密人写出来的正文有没有推翻玩家的操作与引擎的裁决"**。
 *
 * ## 为什么需要这一层（用户 2026-09-30 亲报，项目立意的正中央）
 *
 * 用户的症状是三条，本质是一条：
 *
 * > 「守密人帮玩家做决定」「强行修改剧情」「我说我要开枪、**检定通过**，他说我打歪了」
 * > 「不检定的时候也曲解我的意思」「**禁止我做某些事**」
 *
 * 而提示词里**已经**有六条明确红线（`prompt.ts:103` 不能替玩家说话 ·
 * `:181` 不得替玩家发起新动作 · `:203` 绝不写"你决定前往" · `:230` 绝不替玩家做重大决策 ·
 * `:282` 绝不替玩家出招 · `:431` 绝不替玩家编造自己）。**规则写全了还是被违反**，
 * 说明缺的**不是又一条规则**，而是：**规则说了不算 —— 没人核**。
 *
 * 引擎对**骰子与状态**有裁决权（这是这个项目相对同类产品的立意优势），
 * 但对**叙述**完全没有：正文里写什么，只有模型自己说了算。
 * 于是"引擎裁决成功"与"正文写成失败"可以同时成立，玩家看到的就是自相矛盾。
 *
 * ## 这一层做什么
 *
 * 只做**可判定**的那部分（不猜文风、不做语义理解）：
 *
 * | 判据 | 例子 | 为什么可判定 |
 * |---|---|---|
 * | **结论被推翻** | 引擎裁决"成功"，正文却写"没打中/落了空/被躲开了" | 结论标签与否定词都在固定词表里 |
 * | **动作被掉包** | 玩家说"我开枪"，正文却写"你犹豫了/你收起了枪" | 玩家声明是原文，动作撤销词是有限集合 |
 * | **被禁止/被说教** | "你不能这么做""作为 AI 我不能…""你可以选择 A 或 B" | 已有 `isRefusal` 一族词表 |
 *
 * ⚠️ **这条判据的边界必须写清**：它抓的是**词面矛盾**，不是"写得不好"。
 * 漏网一定会有（模型换一种说法就绕过去了）—— 所以它是**兜底**，
 * 真正的防线仍是提示词；命中后的处置是**重写一次**，不是"判模型错"。
 * 这与 `isCheckLeak` 的分工完全一致（那条注释也写着"仅靠关键词兜底会有漏网"）。
 */

/** 一次检定/裁决的结论，供一致性核对用。 */
export interface VerdictLike {
  /** 技能名或"环境伤害"这类说明 */
  skill: string;
  /** 是否通过 */
  success: boolean;
  /** 是不是大失败（两者都算"否定"，但文案不同） */
  fumble?: boolean;
}

/**
 * 「攻击没有奏效」这一族的词面。
 *
 * ⚠️ 刻意**只在"引擎裁决成功"时才查这些** —— 反过来（裁决失败却写成打中）
 * 同样有害，但那种情况模型更常写对，误判成本更高（"躲开"可能是 NPC 自己躲开别的）。
 */
const MISS_RE =
  /(没打中|没有打中|打偏|打歪|偏了|落(了)?空|扑(了)?空|打空|射空|没击中|未命中|没有命中|被躲开|躲开了|给闪开|闪身避开|擦着|只擦到|没能|无法|不能|做不到|收起了|放下枪|停手了|犹豫)/;

/** 「玩家被执行」这一族的词面：把玩家的动作改写成"没做/改做别的"。 */
const ACTION_OVERRIDE_RE =
  /(你(决定|选择|打算|最终)(不|没有|放弃)|你(改变|改)(了)?(主意|想法)|你没有(动手|开枪|出手|上前)|你(停下|住手|收手)了|你(犹豫)(了|着)|你(放弃)了|你(转身)(离开|走了)|你(默默)(收起))/;

/** 「禁止/说教/菜单」这一族 —— 与 `isRefusal` 同源，但这里只看叙述层。 */
const FORBID_RE = new RegExp(
  [
    '你不能(这么|这样做)',
    '你不可以',
    '这(是)?不允许的',
    '作为(一个)?(AI|人工智能|语言模型)',
    '你可以(选择|尝试)[\\uFF1A:]', // 全角/半角冒号
  ].join('|')
);

/** 命中的违规类别。 */
export type NarrationViolation =
  | 'verdict-contradicted'
  | 'action-overridden'
  | 'forbidden-or-preachy';

export interface ViolationReport {
  kind: NarrationViolation;
  /** 给开发者看的证据片段（命中的词） */
  evidence: string;
}

/**
 * 核一段正文有没有推翻这一轮的裁决。
 *
 * @param body     模型写的叙事正文（不含 JSON 契约）
 * @param declared 玩家这一轮声明的动作原文（可为空 = 这一轮不是玩家行动）
 * @param verdicts 这一轮已经生效的裁决（检定结果等；空 = 这一轮没有裁决）
 *
 * 返回空数组 = 没发现问题（**不等于"一定没问题"**，见文件头的边界说明）。
 */
export function verifyNarration(
  body: string,
  declared: string | null,
  verdicts: readonly VerdictLike[]
): ViolationReport[] {
  const out: ViolationReport[] = [];
  const text = body ?? '';

  /*
   * ① 裁决被推翻：引擎说"成功"，正文却写"没打中 / 落空"。
   *
   * 只查"成功"的裁决：失败却写得像成功，同样有害，但那种写法更常出现在
   * "玩家自己掷失败了、模型写成被挡开"这种**本来就对**的叙述里，误判成本太高。
   */
  const succeeded = verdicts.filter((v) => v.success);
  if (succeeded.length > 0) {
    const m = MISS_RE.exec(text);
    if (m) {
      out.push({
        kind: 'verdict-contradicted',
        evidence: `${succeeded.map((v) => v.skill).join('、')} 已判定成功，正文却出现「${m[1]}」`,
      });
    }
  }

  /*
   * ② 玩家的动作被掉包：玩家声明了要做某件事，正文却写成"他没做/改主意了"。
   * 只在**这一轮确实有玩家声明**时才查 —— 否则（比如开场白）会误判。
   */
  if (declared && declared.trim()) {
    const m = ACTION_OVERRIDE_RE.exec(text);
    if (m) {
      out.push({
        kind: 'action-overridden',
        evidence: `玩家声明「${declared.trim().slice(0, 24)}」，正文却写「${m[1]}」`,
      });
    }
  }

  // ③ 禁止 / 说教 / 列菜单
  const m = FORBID_RE.exec(text);
  if (m) {
    out.push({ kind: 'forbidden-or-preachy', evidence: `正文出现「${m[1]}」` });
  }

  return out;
}

/**
 * 命中违规时追加的纠正指令。
 *
 * 与 `RETRY_NOTE` / `CHECK_RETRY_NOTE` 同族：**只说"你错了"没用，必须说清哪里错、怎么改。**
 * 所以这里把命中的证据（引擎裁决 vs 正文原文）带进指令里。
 */
export const NARRATION_RETRY_NOTE =
  '【系统纠正·玩家操作必须被尊重】你上一条回复**推翻了玩家的操作或引擎已经定下的结果**。\n' +
  '三条不可越过的底线：\n' +
  '1. **玩家声明要做什么，就是他在做什么** —— 不许改写成"他犹豫了/他放弃了/他决定不去"，' +
  '更不许写成"你不能这么做"。你只写**世界如何反应**。\n' +
  '2. **引擎已经判定成功的事，不许在正文里写成失败**（"没打中/落空/被躲开"）。' +
  '成功就写它造成的后果（该见血就见血），失败才写代价。\n' +
  '3. **不许说教、不许列选项菜单**（"你可以选择 A 或 B"）、不许以 AI 身份说话。\n' +
  '如果某个动作在**机制上**确实做不到（例如玩家根本没带那把武器），' +
  '就把原因写成**故事里的一个事实**（"你摸向腰间——枪套是空的"），**不要宣布玩家不能行动**，' +
  '也不要替他改主意。请重写这一段。';

/** 占位导出，供测试断言"词表与纠正指令配套"。 */
export const NARRATION_VERIFIER_RE = { MISS_RE, ACTION_OVERRIDE_RE, FORBID_RE };
