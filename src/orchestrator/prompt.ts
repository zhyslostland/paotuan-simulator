/** 检测到检定结果泄漏时追加的纠正指令 */
export const CHECK_RETRY_NOTE =
  '【系统纠正】你上一条回复的正文里出现了"检定 / 判定 / 掷骰 / 成功 / 失败"这类字样，这是不允许的。' +
  '检定结果会由引擎单独渲染成一张卡片显示给玩家，正文里**一个字都不能提**。请重写这一轮：' +
  '需要检定就只放进 dice_requests；正文只写 NPC 与环境的反应，把结论**化成事实**（' +
  '"你侦查成功，发现地板上有刮痕" → 改成"地板接缝处有几道新鲜的刮痕"；' +
  '"说服失败" → 改成"老人抿紧嘴唇，把头偏向了窗外"），并且不要替玩家发起任何新动作。';

/*
 * 契约缺失时**不再整段重写正文**（见 `CONTRACT_ONLY_NOTE`）。
 * 原因：重写会让屏幕上闪一下空白，代价远大于"这一轮状态不推进"。
 * 旧版的 CONTRACT_RETRY_NOTE 已移除，不要再加回来。
 */

/**
 * 兜底：模型偶尔会把"移动意图"这串模板原样抄进正文（"我打算前往……请用剧情里的理由把我拦下"）。
 * 玩家看到自己的指令被念出来非常出戏，这里把这类括号块整段删掉。
 * 只匹配那几个**只会出现在模板里**的短语，避免误伤正常叙事。
 */
const TRAVEL_ECHO_RE =
  /[（(][^）)]{0,60}(?:我打算前往|如果现在去不了|把我拦下|这只是我(?:此刻)?的打算|意图\s*[:：]?\s*前往)[^）)]{0,60}[）)]/g;
/** 单独一行的"纯意图"括号（如「（意图：前往「码头区」）」），整行删掉 */
const TRAVEL_ECHO_LINE_RE = /^[ \t]*[（(]\s*意图\s*[:：][^）)]*[）)][ \t]*$/gm;

export function stripTravelEcho(text: string): string {
  /*
   * 注意：正则里的短语必须覆盖**当前** `travelTo` 发出的模板。
   * 早期只写了旧模板（"我打算前往…"），换了新模板（"（意图：前往「X」）"）却没同步，
   * 兜底形同虚设——而提示词里又把这个新串当范例写给了模型，等于亲手教它照抄（协作方 N1）。
   */
  if (!TRAVEL_ECHO_RE.test(text) && !TRAVEL_ECHO_LINE_RE.test(text)) return text;
  TRAVEL_ECHO_RE.lastIndex = 0;
  TRAVEL_ECHO_LINE_RE.lastIndex = 0;
  return text
    .replace(TRAVEL_ECHO_LINE_RE, '')
    .replace(TRAVEL_ECHO_RE, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/** 缺失契约时的"只补契约"指令：不重写正文，只要 JSON 块 */
export const CONTRACT_ONLY_NOTE =
  '（系统）你上一段叙事已经通过，不要重写它。现在**只输出**末尾的 ```json 契约块，' +
  '严格对应刚才那段剧情：npc_lines / dice_requests / state_delta / location / summary_delta 如实填写，' +
  '没有内容就给空数组或空值。不要输出任何叙事文字，JSON 块之后也不要再写任何东西。';

/** 从模型输出尾部提取 JSON 契约块；失败返回 null（有降级路径） */
export function extractContract(text: string): {
  body: string;
  contract: {
    npc_lines?: NpcLine[];
    dice_requests?: { skill: string; difficulty?: string; reason?: string }[];
    state_delta?: {
      target: string;
      op: string;
      value?: unknown;
      amount?: number | string;
      reason?: string;
    }[];
    location?: string;
    summary_delta?: string;
    /**
     * 收束声明：守密人判断"模组预设的某个结局真的成立了"时填。
     * 引擎据此结档（App 会去要一段结局正文），而不是让故事无限续写下去。
     */
    ending?: { kind?: string; reason?: string };
  } | null;
} {
  const fenceRe = /```(?:json)?\s*([\s\S]*?)```/g;
  let last: RegExpExecArray | null = null;
  let m: RegExpExecArray | null;
  while ((m = fenceRe.exec(text)) !== null) last = m;

  if (!last) return { body: text.trim(), contract: null };

  const raw = last[1]!.trim();
  if (!raw.startsWith('{')) return { body: text.trim(), contract: null };

  try {
    const parsed = JSON.parse(raw);
    const body = text.slice(0, last.index).trim();
    return { body, contract: parsed };
  } catch {
    // JSON 解析失败：保留全文，契约丢弃，走降级
    return { body: text.trim(), contract: null };
  }
}
