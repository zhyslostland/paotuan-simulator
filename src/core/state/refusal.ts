/**
 * 拒绝话术 —— **引擎在拒绝一次变更时，对玩家说什么**。
 *
 * ## 为什么单独抽一个文件（2026-09-30 · 用户亲报「检定通过却说我打歪了」）
 *
 * 引擎拒绝本身是**对的**（引擎权威是本项目第一条铁律）。出问题的是**话术**：
 *
 * - `gameState.ts` 的命中闸门在 `ctx.foeDamage === 'miss'` 时写的是
 *   「**这一下没打中**（攻击检定没过），「巨影」不该掉血」。
 * - 而玩家那一轮看到的检定卡片是**成功**。
 *
 * 于是屏幕上是两句话互相打架：卡片说成功、状态变化说没打中。
 * **玩家无从知道该信哪一句** —— 这就是"我要开枪、检定通过、他说我打歪了"的机制来源。
 *
 * ## 两条语言纪律（这个文件存在的意义）
 *
 * 1. **引擎拒绝 ≠ 判定**。"没掷 / 掷了没过"与"伤害不成立"是**两件事**。
 *    前者说的是玩家那一掷，后者说的是这次申报能不能落地 —— 不能混在一句话里。
 * 2. **机制性原因要说机制**（没带武器、目标不在场），**不要用判定语言**
 *    （"没打中"读起来像"你掷输了"）。玩家读到的每一句都该让他知道**下一步能做什么**。
 *
 * ⚠️ 与 `orchestrator/narration.ts` 的分工：
 * - `narration.ts` 管**模型正文**（叙述层）；
 * - 这里管**引擎自己发给玩家的那句理由**（状态变化卡片那一栏）。
 * 两者是同一件事的两端，**别各写一套话术**。
 */

/** 玩家那一掷的结果（由 store 从最近一次检定给出）。 */
export type AttackGrant = 'hit' | 'miss' | 'none';

/**
 * 武器伤害申报被拒时，给玩家的理由。
 *
 * @param name       目标名字（"雾中的巨影"）
 * @param grant      最近一次检定给的命中授权
 * @param hasWeapon  申报里是否写了武器名（写了才走命中闸门）
 */
export function attackRejectedReason(name: string, grant: AttackGrant, hasWeapon: boolean): string {
  if (hasWeapon && grant === 'none') {
    // 这一轮压根没掷过：引擎没有依据认定这一下打中
    return `这一轮还没掷过攻击检定，对「${name}」的伤害先不算 —— 掷一次攻击检定，或者把它写成环境造成的伤害（坠落、被砸这类，要写 reason）`;
  }
  if (hasWeapon && grant === 'miss') {
    /*
     * ⚠️ 这句是本次修的重点。
     *
     * 原文是「这一下没打中（攻击检定没过）」—— 把"伤害不成立"说成了"你没打中"。
     * 但玩家那一轮的卡片可能显示**成功**（例如骰点过了、却因为别的原因这一条伤害不成立），
     * 两句话放在一起就是自相矛盾。
     *
     * 现在改成**陈述机制事实**：伤害没有落地，原因在这一条申报上，而不是在玩家那一掷上；
     * 并且**指向玩家能立刻做的事**。至于"打中了没有"由正文与检定卡片去说，
     * 引擎不抢那句话（`orchestrator/narration.ts` 会核正文有没有推翻卡片）。
     */
    return `这次伤害没有落地（引擎按「攻击检定未通过」拦下了它），「${name}」的血先不扣 —— 若这一下确实应该奏效，请在下一轮重新掷一次攻击检定`;
  }
  // 兜底：不该走到这里（只有 weapon 才进闸门），但话术必须仍然是人话
  return `对「${name}」的这次伤害没有落地 —— 请重新申报，或先掷一次攻击检定`;
}

