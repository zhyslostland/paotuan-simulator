/** 默认口吻。**必须**是"加了这一层之前就是这个调子"的那一个 —— 没选过的人不该被换一种声音 */
export const DEFAULT_GM_VOICE: GmVoice = 'storyteller';

/** 按 id 取定义；认不出来（旧存档 / 手改存档）就退回默认，绝不返回 undefined 让提示词拼出 "undefined" */
export function gmVoiceOf(id: string | undefined | null): GmVoiceDef {
  const hit = GM_VOICES.find((v) => v.id === id);
  return hit ?? GM_VOICES.find((v) => v.id === DEFAULT_GM_VOICE)!;
}

/** 界面用：可选项列表 */
export function listGmVoices(): readonly GmVoiceDef[] {
  return GM_VOICES;
}
