/**
 * 守密人（GM）口吻预设 —— R8。
 *
 * ## 为什么要有这一层
 * 现在的提示词把"怎么讲"管得很细（第二人称、禁游戏术语、不替玩家做决定……），
 * 但**没有管"用谁的声音讲"**。结果四个人开同一个模组，听到的都是同一种调子 ——
 * 而"调子"恰恰是跑团里最私人、也最影响沉浸的一样东西。
 *
 * ## 四条设计约束
 * 1. **只改说法，不改规则。** 口吻是"怎么说"，规则是"发生什么"。
 *    这一层**绝不能**改变：谁掷骰、数值怎么算、状态怎么变、真相什么时候给。
 *    所以每段口吻都得写在既有红线**之下**（红线照旧，口吻只是叠加一层笔调）。
 * 2. **四种口吻都不允许替玩家做决定。** 哪怕是最"有存在感"的老派说书人，
 *    也只能评点，不能替他选。这是用户的一条硬规矩（"以玩家为中心"）。
 * 3. **默认项必须等于"现在的写法"。** 玩家没选的时候，听到的应该跟没做这个功能之前一样 ——
 *    默认口吻是**零改动**的那一个（老派说书人），不是"新增了一种风格"。
 * 4. **写法要能被单测。** 段落是纯常量，判断"某个 id 有没有定义"是纯函数。
 *
 * ## 为什么是这四种
 * 覆盖"叙述者存在感"这条轴上的四个位置：
 * 说书人（露面、会评点）→ 旁白（不露面、只给画面）→ 搭档（进场、跟你一起）→ 命运之声（高悬、宣示）。
 */

/** 口吻 id。存档里存的就是这个字符串，改名字要写迁移 */
export type GmVoice = 'storyteller' | 'narrator' | 'partner' | 'fate';

export interface GmVoiceDef {
  id: GmVoice;
  /** 界面上显示的名字 */
  label: string;
  /** 一句话说明（给玩家看，选的时候知道会变成什么样） */
  hint: string;
  /** 注入提示词的整段写法要求 */
  prompt: string;
}

